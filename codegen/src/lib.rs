#[derive(Debug, Clone)]
pub struct Variant {
    pub pascal: String,
    pub wire: String,
    pub doc: String,
}

#[derive(Debug, Clone)]
pub struct ChiSpec {
    pub version: String,
    pub chi: Vec<Variant>,
    pub pulse: Vec<Variant>,
}

pub fn parse(chi_rs: &Path, lib_rs: &Path, wire_md: &Path) -> Result<ChiSpec> {
    let chi_src =
        fs::read_to_string(chi_rs).with_context(|| format!("read {}", chi_rs.display()))?;
    let lib_src =
        fs::read_to_string(lib_rs).with_context(|| format!("read {}", lib_rs.display()))?;
    let wire_src =
        fs::read_to_string(wire_md).with_context(|| format!("read {}", wire_md.display()))?;
    let mut chi = extract_enum(&chi_src, "Chi")?;
    let mut pulse = extract_enum(&chi_src, "PulseKind")?;
    let docs = extract_wire_docs(&wire_src)?;
    for v in chi.iter_mut() {
        let Some(doc) = docs.get(&v.wire) else {
            bail!(
                "chi `{}` ({}) has no row in {}",
                v.wire,
                v.pascal,
                paths::WIRE_MD_REL
            );
        };
        v.doc = doc.clone();
    }
    let pulse_docs = extract_pulse_docs(&wire_src)?;
    for v in pulse.iter_mut() {
        v.doc = pulse_docs.get(&v.wire).cloned().unwrap_or_default();
    }
    Ok(ChiSpec {
        version: extract_version(&lib_src)?,
        chi,
        pulse,
    })
}

