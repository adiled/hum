fn chi_at_generated_header(comment: &str) -> String {
    format!(
        "{c} @generated by `cargo run -p codegen` from {thrum} — DO NOT EDIT.\n\
         {c}\n\
         {c} {thrum} is the thrum. Edit it, and this file is regenerated on\n\
         {c} every cargo build of thrum-core (build.rs). Manual regen:\n\
         {c} `cargo run -p codegen`.\n\n",
        c = comment,
        thrum = paths::HUM_THRUM_REL,
    )
}

#[derive(Debug, Clone)]
pub struct Variant {
    pub pascal: String,
    pub wire: String,
    pub doc: String,
}

#[derive(Debug, Clone)]
pub struct ChiSpec {
    pub version: String,
    pub chi: Vec<Variant>,
    pub pulse: Vec<Variant>,
    pub petal: Vec<Variant>,
    pub role: Vec<Variant>,
}

pub fn emit_ts(spec: &ChiSpec, output: &Path) -> Result<()> {
    let s = render_ts(spec);
    if let Some(parent) = output.parent() {
        fs::create_dir_all(parent).ok();
    }
    fs::write(output, s).with_context(|| format!("write {}", output.display()))?;
    Ok(())
}

