pub(crate) fn extract_version(lib: &str) -> Result<String> {
    let re = Regex::new(r#"pub\s+const\s+THRUM_VERSION\s*:\s*&\s*str\s*=\s*"([^"]+)""#)?;
    let caps = re
        .captures(lib)
        .ok_or_else(|| anyhow!("THRUM_VERSION not found in {}", paths::LIB_RS_REL))?;
    Ok(caps[1].to_string())
}

pub(crate) fn read(path: &Path) -> Result<String> {
    fs::read_to_string(path).with_context(|| format!("read {}", path.display()))
}

pub(crate) fn extract_enum(src: &str, name: &str) -> Result<Vec<Variant>> {
    let opener = Regex::new(&format!(r"pub\s+enum\s+{}\s*\{{", regex::escape(name)))?;
    let m = opener
        .find(src)
        .ok_or_else(|| anyhow!("`pub enum {}` not found", name))?;
    let body_start = m.end();
    let bytes = src.as_bytes();
    let mut depth = 1usize;
    let mut i = body_start;
    while i < bytes.len() && depth > 0 {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    break;
                }
            }
            _ => {}
        }
        i += 1;
    }
    if depth != 0 {
        bail!("unterminated `{}` block", name);
    }
    let body = &src[body_start..i];

    let mut out = Vec::new();

    for raw_line in body.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        let ident_end = line.find([',', ' ', '#', '(']).unwrap_or(line.len());
        let ident = &line[..ident_end];
        if !ident.chars().next().is_some_and(|c| c.is_ascii_uppercase()) {
            continue;
        }
        let pascal = ident.to_string();
        let wire = pascal_to_kebab(&pascal);
        out.push(Variant {
            pascal,
            wire,
            doc: String::new(),
        });
    }
    if out.is_empty() {
        bail!("`{}` block parsed but yielded no variants", name);
    }
    Ok(out)
}

fn pascal_to_kebab(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('-');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal_to_camel(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) => c.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn pascal_to_screaming_snake(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c);
        } else {
            out.push(c.to_ascii_uppercase());
        }
    }
    out
}


fn render_ts(spec: &ChiSpec) -> String {
    let mut s = String::new();
    s.push_str(&chi_at_generated_header("//"));

    s.push_str(&format!(
        "export const THRUM_VERSION = \"{}\" as const;\n\n",
        spec.version
    ));

    s.push_str("// Every wire-known chi value. Adding a new variant bumps the\n");
    s.push_str("// protocol minor; renaming/removing bumps major.\n");
    s.push_str("export const Chi = {\n");
    for v in &spec.chi {
        if !v.doc.is_empty() {
            s.push_str(&format!("  /** {} */\n", v.doc));
        }
        s.push_str(&format!(
            "  {}: \"{}\",\n",
            pascal_to_camel(&v.pascal),
            v.wire
        ));
    }
    s.push_str("} as const;\n");
    s.push_str("export type ChiKind = typeof Chi[keyof typeof Chi];\n\n");
    s.push_str("export const ALL_CHI: ReadonlySet<ChiKind> = new Set(Object.values(Chi));\n");
    s.push_str("export function isValidChi(s: string): s is ChiKind { return ALL_CHI.has(s as ChiKind); }\n\n");

    s.push_str("// pulse.kind is its own enum within chi:\"pulse\" tones.\n");
    s.push_str("export const PulseKind = {\n");
    for v in &spec.pulse {
        if !v.doc.is_empty() {
            s.push_str(&format!("  /** {} */\n", v.doc));
        }
        s.push_str(&format!(
            "  {}: \"{}\",\n",
            pascal_to_camel(&v.pascal),
            v.wire
        ));
    }
    s.push_str("} as const;\n");
    s.push_str("export type PulseKindT = typeof PulseKind[keyof typeof PulseKind];\n\n");
    s.push_str("// petal.kind says which unit of content a petal is.\n");
    s.push_str("export const PetalKind = {\n");
    for v in &spec.petal {
        if !v.doc.is_empty() {
            s.push_str(&format!("  /** {} */\n", v.doc));
        }
        s.push_str(&format!("  {}: \"{}\",\n", pascal_to_camel(&v.pascal), v.wire));
    }
    s.push_str("} as const;\n");
    s.push_str("export type PetalKindT = typeof PetalKind[keyof typeof PetalKind];\n\n");
    s.push_str("// role is the one job a bee does, set when its hive enters it.\n");
    s.push_str("export const Role = {\n");
    for v in &spec.role {
        if !v.doc.is_empty() {
            s.push_str(&format!("  /** {} */\n", v.doc));
        }
        s.push_str(&format!("  {}: \"{}\",\n", pascal_to_camel(&v.pascal), v.wire));
    }
    s.push_str("} as const;\n");
    s.push_str("export type RoleT = typeof Role[keyof typeof Role];\n");
    s
}


fn render_py(spec: &ChiSpec) -> String {
    let mut s = String::new();
    s.push_str(&chi_at_generated_header("#"));
    s.push_str("from __future__ import annotations\n\n");
    s.push_str(&format!("THRUM_VERSION = \"{}\"\n\n", spec.version));

    s.push_str("class Chi:\n");
    s.push_str("    \"\"\"Every wire-known chi value. Adding a new variant bumps the\n");
    s.push_str("    protocol minor; renaming/removing bumps major.\"\"\"\n");
    for v in &spec.chi {
        if !v.doc.is_empty() {
            s.push_str(&format!("    # {}\n", v.doc));
        }
        s.push_str(&format!(
            "    {}: str = \"{}\"\n",
            pascal_to_screaming_snake(&v.pascal),
            v.wire
        ));
    }
    s.push('\n');

    s.push_str("ALL_CHI: frozenset[str] = frozenset({\n");
    for v in &spec.chi {
        s.push_str(&format!("    \"{}\",\n", v.wire));
    }
    s.push_str("})\n\n");
    s.push_str("def is_valid_chi(value: str) -> bool:\n");
    s.push_str("    return value in ALL_CHI\n\n");

    s.push_str("class PulseKind:\n");
    s.push_str("    \"\"\"pulse.kind enum within chi:'pulse' tones.\"\"\"\n");
    for v in &spec.pulse {
        if !v.doc.is_empty() {
            s.push_str(&format!("    # {}\n", v.doc));
        }
        s.push_str(&format!(
            "    {}: str = \"{}\"\n",
            pascal_to_screaming_snake(&v.pascal),
            v.wire
        ));
    }
    s.push('\n');

    s.push_str("class PetalKind:\n");
    s.push_str("    \"\"\"petal.kind: which unit of content a petal is.\"\"\"\n");
    for v in &spec.petal {
        if !v.doc.is_empty() {
            s.push_str(&format!("    # {}\n", v.doc));
        }
        s.push_str(&format!("    {}: str = \"{}\"\n", pascal_to_screaming_snake(&v.pascal), v.wire));
    }
    s.push('\n');

    s.push_str("class Role:\n");
    s.push_str("    \"\"\"role: the one job a bee does, set when its hive enters it.\"\"\"\n");
    for v in &spec.role {
        if !v.doc.is_empty() {
            s.push_str(&format!("    # {}\n", v.doc));
        }
        s.push_str(&format!("    {}: str = \"{}\"\n", pascal_to_screaming_snake(&v.pascal), v.wire));
    }
    s.push('\n');

    s
}

fn render_go(spec: &ChiSpec) -> String {
    let mut s = String::new();
    s.push_str(&chi_at_generated_header("//"));
    s.push_str("package thrum\n\n");

    s.push_str(&format!("const ThrumVersion = \"{}\"\n\n", spec.version));

    s.push_str("// Chi is the discriminator on every tone.\n");
    s.push_str("type Chi string\n\n");
    s.push_str("// Every wire-known chi value. Adding a new variant bumps the\n");
    s.push_str("// protocol minor; renaming/removing bumps major.\n");
    s.push_str("const (\n");
    for v in &spec.chi {
        if !v.doc.is_empty() {
            s.push_str(&format!("    // {}\n", v.doc));
        }
        s.push_str(&format!("    Chi{} Chi = \"{}\"\n", v.pascal, v.wire));
    }
    s.push_str(")\n\n");

    s.push_str("// AllChi is the set of every known chi value for membership checks.\n");
    s.push_str("var AllChi = map[Chi]struct{}{\n");
    for v in &spec.chi {
        s.push_str(&format!("    Chi{}: {{}},\n", v.pascal));
    }
    s.push_str("}\n\n");
    s.push_str("// IsValidChi returns true if value is a known chi.\n");
    s.push_str("func IsValidChi(value string) bool {\n");
    s.push_str("    _, ok := AllChi[Chi(value)]\n");
    s.push_str("    return ok\n");
    s.push_str("}\n\n");

    s.push_str("// PulseKind is the kind field within chi:\"pulse\" tones.\n");
    s.push_str("type PulseKind string\n\n");
    s.push_str("const (\n");
    for v in &spec.pulse {
        if !v.doc.is_empty() {
            s.push_str(&format!("    // {}\n", v.doc));
        }
        s.push_str(&format!(
            "    PulseKind{} PulseKind = \"{}\"\n",
            v.pascal, v.wire
        ));
    }
    s.push_str(")\n\n");

    s.push_str("// PetalKind is the kind field of a petal, and of an unfurl.\n");
    s.push_str("type PetalKind string\n\n");
    s.push_str("const (\n");
    for v in &spec.petal {
        if !v.doc.is_empty() {
            s.push_str(&format!("    // {}\n", v.doc));
        }
        s.push_str(&format!(
            "    PetalKind{} PetalKind = \"{}\"\n",
            v.pascal, v.wire
        ));
    }
    s.push_str(")\n\n");

    s.push_str("// Role is the one job a bee does, set when its hive enters it.\n");
    s.push_str("type Role string\n\n");
    s.push_str("const (\n");
    for v in &spec.role {
        if !v.doc.is_empty() {
            s.push_str(&format!("    // {}\n", v.doc));
        }
        s.push_str(&format!("    Role{} Role = \"{}\"\n", v.pascal, v.wire));
    }
    s.push_str(")\n");

    s
}

fn c_line_comment(doc: &str) -> String {
    let flat: String = doc
        .chars()
        .map(|c| if c == '\n' || c == '\r' { ' ' } else { c })
        .collect();
    format!("// {}\n", flat.trim_end().trim_end_matches('\\').trim_end())
}

fn render_c_set(s: &mut String, tag: &str, set: &str, variants: &[Variant]) {
    for v in variants {
        if !v.doc.is_empty() {
            s.push_str(&c_line_comment(&v.doc));
        }
        s.push_str(&format!(
            "#define THRUM_{tag}_{} \"{}\"\n",
            pascal_to_screaming_snake(&v.pascal),
            v.wire
        ));
    }
    s.push_str(&format!("\n#define THRUM_{tag}_COUNT {}\n\n", variants.len()));
    if variants.is_empty() {
        s.push_str(&format!(
            "static inline bool thrum_is_valid_{set}(const char *value) {{\n\
             \x20   (void)value;\n\
             \x20   return false;\n\
             }}\n\n"
        ));
        return;
    }
    s.push_str(&format!("static const char *const THRUM_ALL_{tag}[THRUM_{tag}_COUNT] = {{\n"));
    for v in variants {
        s.push_str(&format!(
            "    THRUM_{tag}_{},\n",
            pascal_to_screaming_snake(&v.pascal)
        ));
    }
    s.push_str("};\n\n");
    s.push_str(&format!(
        "static inline bool thrum_is_valid_{set}(const char *value) {{\n\
         \x20   size_t i;\n\
         \x20   if (!value) return false;\n\
         \x20   for (i = 0; i < THRUM_{tag}_COUNT; i++) {{\n\
         \x20       if (strcmp(THRUM_ALL_{tag}[i], value) == 0) return true;\n\
         \x20   }}\n\
         \x20   return false;\n\
         }}\n\n"
    ));
}

fn render_c(spec: &ChiSpec) -> String {
    let mut s = String::new();
    s.push_str(&chi_at_generated_header("//"));
    s.push_str("#ifndef THRUM_CHI_H\n#define THRUM_CHI_H\n\n");
    s.push_str("#include <stdbool.h>\n#include <stddef.h>\n#include <string.h>\n\n");
    s.push_str(&format!("#define THRUM_VERSION \"{}\"\n\n", spec.version));
    render_c_set(&mut s, "CHI", "chi", &spec.chi);
    render_c_set(&mut s, "PULSE", "pulse", &spec.pulse);
    render_c_set(&mut s, "PETAL", "petal", &spec.petal);
    render_c_set(&mut s, "ROLE", "role", &spec.role);
    s.push_str("#endif\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_c_registry_names_every_chi_once() {
        let spec = ChiSpec {
            version: "9.9.9".into(),
            chi: vec![
                Variant { pascal: "Hello".into(), wire: "hello".into(), doc: "first \\".into() },
                Variant { pascal: "TendrilReach".into(), wire: "tendril-reach".into(), doc: String::new() },
            ],
            pulse: vec![],
            petal: vec![Variant { pascal: "Pollen".into(), wire: "pollen".into(), doc: String::new() }],
            role: vec![Variant { pascal: "Nurse".into(), wire: "nurse".into(), doc: String::new() }],
        };
        let c = render_c(&spec);
        assert!(c.contains("#define THRUM_VERSION \"9.9.9\"\n"));
        assert!(c.contains("// first\n#define THRUM_CHI_HELLO \"hello\"\n"));
        assert!(c.contains("#define THRUM_CHI_TENDRIL_REACH \"tendril-reach\"\n"));
        assert!(c.contains("#define THRUM_CHI_COUNT 2\n"));
        assert!(c.contains("#define THRUM_PULSE_COUNT 0\n"));
        assert!(c.contains("#define THRUM_PETAL_POLLEN \"pollen\"\n"));
        assert!(c.contains("#define THRUM_ROLE_NURSE \"nurse\"\n"));
        assert!(c.contains("static inline bool thrum_is_valid_chi(const char *value)"));
    }

    #[test]
    fn kebab_and_camel_are_consistent() {
        assert_eq!(pascal_to_kebab("TendrilReach"), "tendril-reach");
        assert_eq!(pascal_to_kebab("DroneRetrofit"), "drone-retrofit");
        assert_eq!(pascal_to_kebab("Hello"), "hello");
        assert_eq!(pascal_to_camel("TendrilReach"), "tendrilReach");
        assert_eq!(pascal_to_camel("Hello"), "hello");
        assert_eq!(pascal_to_screaming_snake("TendrilReach"), "TENDRIL_REACH");
        assert_eq!(pascal_to_screaming_snake("DroneRetrofit"), "DRONE_RETROFIT");
        assert_eq!(pascal_to_screaming_snake("Hello"), "HELLO");
    }

    #[test]
    fn extracts_version() {
        let src = "use foo;\npub const THRUM_VERSION: &str = \"0.3.0\";\n";
        assert_eq!(extract_version(src).unwrap(), "0.3.0");
    }

    #[test]
    fn extracts_variants() {
        let src = r#"
            pub enum Chi {
                Hello,
                Prompt,
                Wilt,
            }
        "#;
        let vs = extract_enum(src, "Chi").unwrap();
        assert_eq!(vs.len(), 3);
        assert_eq!(vs[0].pascal, "Hello");
        assert_eq!(vs[0].wire, "hello");
        assert_eq!(vs[2].wire, "wilt");
    }
}
