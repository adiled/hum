fn extract_version(lib: &str) -> Result<String> {
    let re = Regex::new(r#"pub\s+const\s+THRUM_VERSION\s*:\s*&\s*str\s*=\s*"([^"]+)""#)?;
    let caps = re
        .captures(lib)
        .ok_or_else(|| anyhow!("THRUM_VERSION not found in lib.rs"))?;
    Ok(caps[1].to_string())
}

fn extract_enum(src: &str, name: &str) -> Result<Vec<Variant>> {
    let opener = Regex::new(&format!(r"pub\s+enum\s+{}\s*\{{", regex::escape(name)))?;
    let m = opener
        .find(src)
        .ok_or_else(|| anyhow!("`pub enum {}` not found", name))?;
    let body_start = m.end();
    let bytes = src.as_bytes();
    let mut depth = 1usize;
    let mut i = body_start;
    while i < bytes.len() && depth > 0 {
        match bytes[i] {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    break;
                }
            }
            _ => {}
        }
        i += 1;
    }
    if depth != 0 {
        bail!("unterminated `{}` block", name);
    }
    let body = &src[body_start..i];

    let mut out = Vec::new();

    for raw_line in body.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        let ident_end = line.find([',', ' ', '#', '(']).unwrap_or(line.len());
        let ident = &line[..ident_end];
        if !ident.chars().next().is_some_and(|c| c.is_ascii_uppercase()) {
            continue;
        }
        let pascal = ident.to_string();
        let wire = pascal_to_kebab(&pascal);
        out.push(Variant {
            pascal,
            wire,
            doc: String::new(),
        });
    }
    if out.is_empty() {
        bail!("`{}` block parsed but yielded no variants", name);
    }
    Ok(out)
}

fn extract_wire_docs(wire_md: &str) -> Result<HashMap<String, String>> {
    let mut docs = HashMap::new();
    for line in wire_md.lines() {
        let line = line.trim();
        if !line.starts_with('|') {
            continue;
        }
        let cells: Vec<&str> = line
            .trim_matches('|')
            .split('|')
            .map(str::trim)
            .collect();
        if cells.len() != 4 {
            continue;
        }
        let Some(wire) = cells[0].strip_prefix('`').and_then(|c| c.strip_suffix('`')) else {
            continue;
        };
        if wire.is_empty() || wire.contains(' ') {
            continue;
        }
        let description = cells[3];
        if description.is_empty() {
            continue;
        }
        docs.insert(wire.to_string(), description.to_string());
    }
    if docs.is_empty() {
        bail!("no chi descriptions found in WIRE.md");
    }
    Ok(docs)
}

fn extract_pulse_docs(wire_md: &str) -> Result<HashMap<String, String>> {
    let mut docs = HashMap::new();
    let mut in_pulse = false;
    for line in wire_md.lines() {
        let line = line.trim();
        if line.starts_with("### ") {
            in_pulse = line.contains("pulse.kind");
            continue;
        }
        if !in_pulse || !line.starts_with('|') {
            continue;
        }
        let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
        if cells.len() != 2 {
            continue;
        }
        let Some(kind) = cells[0].strip_prefix('`').and_then(|c| c.strip_suffix('`')) else {
            continue;
        };
        if kind.is_empty() {
            continue;
        }
        docs.insert(kind.to_string(), cells[1].to_string());
    }
    if docs.is_empty() {
        bail!("no pulse.kind descriptions found in WIRE.md");
    }
    Ok(docs)
}

fn pascal_to_kebab(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('-');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal_to_camel(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) => c.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn pascal_to_screaming_snake(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c);
        } else {
            out.push(c.to_ascii_uppercase());
        }
    }
    out
}


